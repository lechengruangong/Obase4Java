package io.obase.test.domain.association.implement;

/**
 * 车筐
 */
public class BikeBucket {

    /**
     * 车筐编码
     */
    private String code;

    /**
     * 车筐大小
     */
    private String sp;

    /**
     * 获取车筐编码
     *
     * @return 车筐编码
     */
    public String getCode() {
        return this.code;
    }

    /**
     * 设置车筐编码
     *
     * @param code 车筐编码
     */
    public void setCode(String code) {
        this.code = code;
    }

    /**
     * 获取车筐大小
     *
     * @return 车筐大小
     */
    public String getSp() {
        return this.sp;
    }

    /**
     * 设置车筐大小
     *
     * @param sp 车筐大小
     */
    public void setSp(String sp) {
        this.sp = sp;
    }
}
