package io.obase.test.domain.association.implement;

/**
 * 车旗子
 */
public class BikeFlag {

    /**
     * 车旗子编码
     */
    private String code;

    /**
     * 车旗子文字
     */
    private String value;

    /**
     * 获取车旗子编码
     *
     * @return 车旗子编码
     */
    public String getCode() {
        return this.code;
    }

    /**
     * 设置车旗子编码
     *
     * @param code 车旗子编码
     */
    public void setCode(String code) {
        this.code = code;
    }

    /**
     * 获取车旗子文字
     *
     * @return 车旗子文字
     */
    public String getValue() {
        return this.value;
    }

    /**
     * 设置车旗子文字
     *
     * @param value 车旗子文字
     */
    public void setValue(String value) {
        this.value = value;
    }
}
