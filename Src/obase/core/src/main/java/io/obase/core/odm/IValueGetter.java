package io.obase.core.odm;

/**
 * 对象取值器接口
 * 对象取值器用于从对象中获取其属性、关联引用或关联端的值。
 */
public interface IValueGetter {

    /**
     * 从指定对象取值
     *
     * @param obj 目标对象
     * @return 值
     */
    Object getValue(Object obj);
}
