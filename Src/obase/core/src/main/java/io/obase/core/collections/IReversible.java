package io.obase.core.collections;

/**
 * 反序接口
 *
 * @param <T> 元素
 */
public interface IReversible<T> {

    /**
     * 创建一个从当前巨量集合中反序读取元素的只进读取器
     *
     * @return 生成的只进读取器
     */
    IForwardReaderGeneric<T> reverse();
}
