package io.obase.core.query;

/**
 * 枚举集运算的运算符
 */
public enum ESetOperator {

    /**
     * 求并集（不去重）
     */
    Concat,

    /**
     * 求交集
     */
    Interact,

    /**
     * 求差集
     */
    Except,

    /**
     * 求并集（去重）
     */
    Union
}
