package io.obase.common;

/**
 * 元组接口
 */
public interface Tuple {

    /**
     * 获取元组的泛型参数类型集合
     *
     * @return 元组的泛型参数类型集合
     */
    Class<?>[] getGenericClasses();

    /**
     * 获取元组的所有元素
     *
     * @return 元组的所有元素
     */
    Object[] getItems();
}
